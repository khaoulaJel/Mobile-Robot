#!/usr/bin/env python3
"""Build the symbolic model, its transition table and the controller for the 1 m-diameter circle.

Outputs
  config/symbolic_circle.npz              deployable controller (domain cells + policy per goal), a few MB
  results/symbolic/transition_table_excerpt.csv   human-readable excerpt: ALL successors of chosen (cell, input)
  results/symbolic/summary.md             sizes, winning sets, guaranteed step counts
  --full-table PATH                       optional: the complete table in CSR form (hundreds of MB)

Usage: python3 generate_symbolic.py [--out-config ...] [--out-results ...] [--full-table table.npz]
"""
import argparse
import math
import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
from lab3_controllers import symbolic as sy  # noqa: E402

PARAMS = dict(radius=0.5, tube=0.08, dx=0.005, n_th=72, v=0.1, tau=1.0, heading_band=math.radians(45.0), n_goals=12)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out-config', default=os.path.join(HERE, '..', 'config', 'symbolic_circle.npz'))
    ap.add_argument('--out-results', default=os.path.join(HERE, '..', '..', '..', 'results', 'symbolic'))
    ap.add_argument('--full-table', default='')
    a = ap.parse_args()
    os.makedirs(a.out_results, exist_ok=True)
    k = max(3, int(round(0.5 / (2 * math.pi / PARAMS['n_th']) * PARAMS['tau'])))
    t0 = time.time()
    ab, goals, info = sy.circle_setup(turn_cells=tuple(range(-k, k + 1)), **PARAMS)
    t_setup = time.time() - t0
    t0 = time.time()
    ab.build()
    t_build = time.time() - t0
    M = len(ab.inputs)
    print(f'states N={ab.N}, inputs M={M}, (state,input) pairs={ab.N * M}, table entries={len(ab.succ)}')
    pols, ranks = [], []
    t0 = time.time()
    for g in goals:
        r, p = ab.synthesize(g)
        ranks.append(r)
        pols.append(p)
    t_syn = time.time() - t0
    q0 = ab.state_index(0.0, 0.0, 0.0)
    legs, wins = [], []
    for i, r in enumerate(ranks):
        wins.append(100.0 * float((r < sy.INF).mean()))
        if i == 0:
            legs.append(int(r[q0]) if q0 < ab.N and r[q0] < sy.INF else -1)
        else:
            prev = goals[i - 1]
            legs.append(int(r[prev].max()) if (r[prev] < sy.INF).all() else -1)
    print('guaranteed steps per leg (start, then from ANY cell of the previous goal):', legs)
    meta = dict(PARAMS, heading_band=math.degrees(PARAMS['heading_band']), centre_x=0.0, centre_y=PARAMS['radius'])
    pol = sy.Policy.from_abstraction(ab, pols, goals, meta, ranks)
    os.makedirs(os.path.dirname(os.path.abspath(a.out_config)), exist_ok=True)
    pol.save(a.out_config)
    mb = os.path.getsize(a.out_config) / 1e6
    print(f'saved controller {a.out_config} ({mb:.1f} MB)')

    # human-readable excerpt of the transition table: the start cell and a few other cells, every input
    picks = [q0] + list(np.random.default_rng(0).choice(ab.N, 3, replace=False))
    with open(os.path.join(a.out_results, 'transition_table_excerpt.csv'), 'w') as f:
        f.write('cell_ix,cell_iy,cell_ith,cell_centre_x_m,cell_centre_y_m,cell_centre_theta_deg,input_v_mps,'
                'input_w_radps,n_successors,successors(ix iy ith | OUT)\n')
        for q in picks:
            ix, iy, ith = ab.cells[q]
            cx, cy, cth = ab.centre(ix, iy, ith)
            for m in range(M):
                succ = ab.successors(q, m)
                txt = ' ; '.join('OUT' if s == ab.OUT else '%d %d %d' % tuple(ab.cells[s]) for s in succ)
                f.write(f'{ix},{iy},{ith},{cx:.4f},{cy:.4f},{math.degrees(cth):.1f},{ab.inputs[m, 0]:.3f},'
                        f'{ab.inputs[m, 1]:.4f},{len(succ)},"{txt}"\n')
    if a.full_table:
        np.savez_compressed(a.full_table, indptr=ab.indptr, succ=ab.succ, cells=ab.cells.astype(np.int16),
                            inputs=ab.inputs, out_index=ab.OUT)
        print('full table saved', a.full_table, f'({os.path.getsize(a.full_table) / 1e6:.0f} MB)')
    cnt = np.diff(ab.indptr)
    with open(os.path.join(a.out_results, 'summary.md'), 'w') as f:
        f.write('# Symbolic model of the circle problem (generated by tools/generate_symbolic.py)\n\n')
        f.write('| item | value |\n| --- | --- |\n')
        f.write(f"| model | unicycle (x, y, theta), constant (v, w) held for tau |\n")
        f.write(f"| circle | radius {PARAMS['radius']} m (1 m diameter), tangent start at (0, 0), counter-clockwise |\n")
        f.write(f"| safe tube | +-{PARAMS['tube'] * 100:.0f} cm around the circle, heading within +-"
                f"{math.degrees(PARAMS['heading_band']):.0f} deg of the tangent |\n")
        f.write(f"| cell size | {PARAMS['dx'] * 100:.1f} cm x {PARAMS['dx'] * 100:.1f} cm x {360 / PARAMS['n_th']:.0f} deg |\n")
        f.write(f"| sampling time tau | {PARAMS['tau']} s |\n")
        f.write(f"| inputs | v = {PARAMS['v']} m/s, w in {np.round(ab.inputs[:, 1], 3).tolist()} rad/s ({M} inputs; each "
                f"turns the heading by a whole number of cells) |\n")
        f.write(f"| states (cells inside the tube) | {ab.N} |\n")
        f.write(f"| (state, input) pairs | {ab.N * M} |\n")
        f.write(f"| transition entries (successor cells) | {len(ab.succ)} |\n")
        f.write(f"| successors per (state, input) | mean {cnt.mean():.1f}, max {cnt.max()} |\n")
        f.write(f"| goals | {PARAMS['n_goals']} arcs of the circle |\n")
        f.write(f"| winning states per goal | {min(wins):.1f} % to {max(wins):.1f} % of all states |\n")
        f.write(f"| guaranteed steps per leg | {legs} (start, then from ANY cell of the previous goal) = "
                f"{max(legs) * PARAMS['tau']:.0f} s worst case per leg |\n")
        f.write(f"| build / synthesis time | {t_setup + t_build:.0f} s / {t_syn:.0f} s |\n")
        f.write(f"| deployable controller | config/symbolic_circle.npz ({mb:.1f} MB) |\n")
    print('summary written; build %.0f s, synthesis %.0f s' % (t_setup + t_build, t_syn))
    return 0 if all(l >= 0 for l in legs) else 1


if __name__ == '__main__':
    sys.exit(main())
