#!/usr/bin/env python3
"""Strict check + report for the lab-robot preset on the professor's plant (model, no ROS).

Runs 14 shapes with the old competition settings and with config/lab_robot.yaml on the identified plant
(+ robot input filter), prints a table, writes results/lab_robot_results.md and exits non-zero if any
acceptance threshold is missed.
Usage: python3 lab_robot_report.py [--out path/to/lab_robot_results.md]
"""
import argparse
import os
import sys
from concurrent.futures import ProcessPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, '..'))
import robustness as rb  # noqa: E402
import shape_bench as sb  # noqa: E402
import tune_lab_plant as tp  # noqa: E402
import yaw_bench as yb  # noqa: E402

try:
    import yaml
except ImportError:      # the preset file is then not cross-checked
    yaml = None

LAB_PRESET = dict(tp.FIXED)
LAB_PRESET.update(rb.CANDIDATE)
COMPETITION = dict(tp.ROBOT)        # old defaults of controllers.yaml, only the robot's own filter active

# acceptance thresholds, noise-free, waypoint spacing 0.1 m (a little above the worst value seen)
TH = dict(xtrk_max=2.0, final_pos=1.0, final_yaw=0.8, yaw_settle=15.0, yaw_over=4.0, yaw_final=0.6)


def one(args):
    name, over, shape = args
    return sb.run_all(0.1, 0.15, ['stop_turn'], over={'stop_turn': over}, plant='identified', only=[shape],
                      settle=12.0)[0]


def check_yaml():
    """The shipped preset must equal the parameter set that was tuned and benchmarked."""
    if yaml is None:
        return ['PyYAML not available: config/lab_robot.yaml could not be cross-checked']
    path = os.path.join(HERE, '..', 'config', 'lab_robot.yaml')
    with open(path) as f:
        cfg = yaml.safe_load(f)['motion_controller']['ros__parameters']
    bad = []
    for k, v in LAB_PRESET.items():
        if k not in cfg or abs(float(cfg[k]) - float(v)) > 1e-9:
            bad.append(f'lab_robot.yaml {k}={cfg.get(k)} differs from the benchmarked value {v}')
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='')
    a = ap.parse_args()
    shapes = list(sb.shapes())
    jobs = [(n, o, s) for n, o in (('competition', COMPETITION), ('lab_robot', LAB_PRESET)) for s in shapes]
    with ProcessPoolExecutor(max(1, (os.cpu_count() or 2) - 1)) as ex:
        rows = list(ex.map(one, jobs))
    comp = dict(zip(shapes, rows[:len(shapes)]))
    lab = dict(zip(shapes, rows[len(shapes):]))
    failures = []
    md = ["# Lab-robot results (simulation of the professor's plant, not the real robot)", '',
          "Plant: order-4 velocity model identified from the supplied dataset (provenance unverified) behind the "
          "professor's `input_filter` (feasible diamond, deadband). Waypoint spacing 0.1 m, noise-free, errors "
          "measured at rest after 12 s. `competition` = the earlier Gazebo-tuned settings with only the robot's "
          "own filter added, `lab_robot` = `config/lab_robot.yaml`. Generated by `tools/lab_robot_report.py`.", '',
          '## Paths (stop_turn)', '',
          '| shape | settings | done | time [s] | max cross-track [cm] | rms [cm] | final pos [cm] | final yaw [deg] |',
          '| --- | --- | --- | --- | --- | --- | --- | --- |']
    print(f"{'shape':24s} {'settings':12s} {'done':5s} {'time':>6s} {'xtrk max':>8s} {'rms':>5s} "
          f"{'fin pos':>7s} {'fin yaw':>7s}")
    for s in shapes:
        for label, r in (('competition', comp[s]), ('lab_robot', lab[s])):
            print(f"{s:24s} {label:12s} {str(r['ok']):5s} {r['t']:6.1f} {r['max']:8.2f} {r['rms']:5.2f} "
                  f"{r['fin']:7.2f} {r['yaw']:7.2f}")
            md.append(f"| {s} | {label} | {'yes' if r['ok'] else '**NO**'} | {r['t']:.0f} | {r['max']:.2f} | "
                      f"{r['rms']:.2f} | {r['fin']:.2f} | {r['yaw']:.2f} |")
        r = lab[s]
        if not r['ok']:
            failures.append(f'{s}: path not completed')
        else:
            if r['max'] > TH['xtrk_max']:
                failures.append(f"{s}: cross-track {r['max']:.2f} cm > {TH['xtrk_max']}")
            if r['fin'] > TH['final_pos']:
                failures.append(f"{s}: final position error {r['fin']:.2f} cm > {TH['final_pos']}")
            if r['yaw'] > TH['final_yaw']:
                failures.append(f"{s}: final heading error {r['yaw']:.2f} deg > {TH['final_yaw']}")

    md += ['', '## Yaw controller (references 90, -90, 170, -170, 0 deg, 45 s each)', '',
           '| settings | reference [deg] | settling to +-0.5 deg [s] | overshoot [deg] | final error [deg] |',
           '| --- | --- | --- | --- | --- |']
    for label, prm in (('legacy P law', dict(kp=1.0, **yb.ROBOT)), ('lab_robot', yb.LAB)):
        for r in yb.run(prm, 45.0):
            print(f"yaw {label:12s} ref {r['ref']:7.1f}: settle {r['settle']:5.1f} s over {r['over']:5.2f} "
                  f"final {r['final']:6.2f}")
            never = ' (never)' if r['settle'] >= 45.0 else ''
            md.append(f"| {label} | {r['ref']:.0f} | {r['settle']:.1f}{never} | {r['over']:.2f} | {r['final']:.2f} |")
            if label == 'lab_robot':
                if r['settle'] > TH['yaw_settle']:
                    failures.append(f"yaw {r['ref']}: settling {r['settle']:.1f} s > {TH['yaw_settle']}")
                if r['over'] > TH['yaw_over']:
                    failures.append(f"yaw {r['ref']}: overshoot {r['over']:.2f} deg > {TH['yaw_over']}")
                if abs(r['final']) > TH['yaw_final']:
                    failures.append(f"yaw {r['ref']}: final error {r['final']:.2f} deg > {TH['yaw_final']}")
    failures += check_yaml()
    md += ['', '## Acceptance thresholds for `lab_robot`', '',
           '| check | threshold |', '| --- | --- |',
           '| path completed on all 14 shapes | required |',
           f"| max cross-track error | <= {TH['xtrk_max']} cm |",
           f"| final position error | <= {TH['final_pos']} cm |",
           f"| final heading error | <= {TH['final_yaw']} deg |",
           f"| yaw settling / overshoot / final error | <= {TH['yaw_settle']} s / {TH['yaw_over']} deg / "
           f"{TH['yaw_final']} deg |",
           '', f"Result: **{'FAIL' if failures else 'PASS'}**" + ('' if not failures else ' (' + '; '.join(failures) + ')')]
    if a.out:
        with open(a.out, 'w') as f:
            f.write('\n'.join(md) + '\n')
    if failures:
        print('\nFAILED:\n  ' + '\n  '.join(failures))
        return 1
    print('\nPASS: all lab-robot acceptance checks met')
    return 0


if __name__ == '__main__':
    sys.exit(main())
